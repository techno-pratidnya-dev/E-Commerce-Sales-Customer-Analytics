-- Q44. Find the top 5 products with the highest total loss.
SELECT
    p.product_name,
    COUNT(*) AS loss_item_count,
    ROUND(SUM(oi.profit), 2) AS total_loss
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
WHERE oi.profit < 0
GROUP BY p.product_id, p.product_name
ORDER BY SUM(oi.profit) ASC
LIMIT 5;

