-- Q40. Calculate monthly sales and compare them with the previous month.
WITH monthly_sales AS (
    SELECT
        month,
        month_name,
        SUM(sales_amount) AS total_sales
    FROM orders AS o
    INNER JOIN order_items AS oi
        ON o.order_id = oi.order_id
    GROUP BY month, month_name
)
SELECT
    month,
    month_name,
    ROUND(total_sales, 2) AS total_sales,
    ROUND(
        LAG(total_sales) OVER (ORDER BY month),
        2
    ) AS previous_month_sales
FROM monthly_sales
ORDER BY month;

-- Q41. Calculate monthly sales growth percentage.
WITH monthly_sales AS (
    SELECT o.month, SUM(oi.sales_amount) AS sales
    FROM orders o
    JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY o.month
)
SELECT
    month,
    ROUND(sales, 2) AS total_sales,
    ROUND(
        (sales - LAG(sales) OVER (ORDER BY month))
        / LAG(sales) OVER (ORDER BY month) * 100, 2
    ) AS growth_percentage
FROM monthly_sales
ORDER BY month;

-- Q42. Calculate total sales by customer segment.
